"""
Generate MHDuet's slot-in header CCZ4_EE.H: two inline device functions in namespace ee_mhduet, called inside
MHDuet's four fused RHS kernels (AdvanceLevel.cpp), on the shared AMReX backend's MHDuetPointFunction.

- ccz4_rhs(i, j, k, state, aux, prob_lo, dx, parameters, RHS_<component>...): the interior CCZ4 right-hand side of the
  22 spacetime components (add_ccz4_mhduet, ko=False), which MHDuet then passes through its outer-boundary override;
- ccz4_ko(i, j, k, state, aux, prob_lo, dx, parameters, ko_<component>...): their Kreiss-Oliger increments
  (add_ccz4_mhduet_ko), which the host adds after the override, as MHDuet does.

The host binds every output by its name in the emitted signature (mhduet/patch/BINDING-PLAN.md), never by position.

Usage: python generate_mhduet.py [--out-dir DIR]
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from EinsteinEngine import AMReXWizard, MHDuetPointFunction  # noqa: E402
import ccz4_mhduet as R  # noqa: E402
import mhduet_bindings as B  # noqa: E402

parser = argparse.ArgumentParser(description="MHDuet CCZ4 RHS slot-in header (point functions)")
parser.add_argument("--out-dir", default=".", help="directory for CCZ4_EE.H")
args = parser.parse_args()

name, ext = os.path.splitext(B.HEADER)
cc = MHDuetPointFunction(name, fields={b: a for b, (a, _) in B.FIELDS.items() if b not in B.STATE},
                         namespace=B.NAMESPACE, includes=["AmrCoreProblem.H"])


_symbols: dict = {}


def cc_symbol(n: str):
    """Each parameter is declared once, on first use (the recipe asks for some names several times)."""
    if n not in _symbols:
        _symbols[n] = cc.add_param(n)
    return _symbols[n]


rhs = cc.create_function(B.FUNCTIONS["rhs"])
decls = R.add_ccz4_mhduet(cc, rhs, cc_symbol, ko=False, output=cc.output)
ko = cc.create_function(B.FUNCTIONS["ko"])
R.add_ccz4_mhduet_ko(cc, ko, cc_symbol, decls, output=cc.output)
cc.bake()

AMReXWizard(cc, out_dir=args.out_dir, extension=ext).generate_header(
    banner="// Generated by EinsteinEngine from recipes/foreign/mhduet/generate_mhduet.py (recipe ccz4_mhduet.py).\n"
           "// Slot-in for the CCZ4 right-hand side of MHDuet 2.0's fused RHS kernels (AdvanceLevel.cpp):\n"
           "// ee_mhduet::ccz4_rhs gives the interior RHS_<component>, ee_mhduet::ccz4_ko the Kreiss-Oliger\n"
           "// increments ko_<component>, added after MHDuet's outer-boundary override. Bind outputs by name.")
